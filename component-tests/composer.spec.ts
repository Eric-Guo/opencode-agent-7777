test("attachment preparation guards every send route while preserving typing, Stop and native undo", async ({
  page,
}) => {
  const first = Promise.withResolvers<void>()
  const second = Promise.withResolvers<void>()
  await page.route("**/component-tests/attachment?*", async (route) => {
    await (route.request().url().includes("one.txt") ? first.promise : second.promise)
    await route.fulfill({ body: "ready" })
  })
  await page.goto("/component-tests/composer.html?attachments")
  const editor = page.getByRole("textbox", { name: "Message" })
  const input = page.locator('input[type="file"]')
  const send = page.getByRole("button", { name: "Send", exact: true })
  await editor.click()
  await page.keyboard.insertText("draft")
  await input.setInputFiles({ name: "one.txt", mimeType: "text/plain", buffer: Buffer.from("one") })
  await input.setInputFiles({ name: "two.txt", mimeType: "text/plain", buffer: Buffer.from("two") })
  await expect(page.getByRole("status").filter({ hasText: "Preparing attachments" })).toBeVisible()
  await expect(send).toBeDisabled()
  await expect(page.locator('[data-action="composer-alternate-delivery"]')).toHaveCount(0)
  await editor.press("End")
  await page.keyboard.insertText(" edited")
  await editor.press("Enter")
  await editor.press("ControlOrMeta+Enter")
  await page.getByRole("button", { name: "Submit directly", exact: true }).click()
  await page.getByRole("button", { name: "Submit alternate", exact: true }).click()
  await page.locator("form").evaluate((form) => form.requestSubmit())
  await expect(page.getByLabel("Submissions")).toHaveText("0")
  await editor.press("Control+g")
  await expect(page.getByLabel("Stops")).toHaveText("1")
  first.resolve()
  await expect(page.getByLabel("Attachments")).toHaveText("1")
  await expect(send).toBeDisabled()
  second.resolve()
  await expect(page.getByLabel("Attachments")).toHaveText("2")
  await expect(send).toBeEnabled()
  await expect(page.getByLabel("Submissions")).toHaveText("0")
  await expect(editor).toHaveText("draft edited")
  await expect(editor).toBeFocused()
  expect(await editor.evaluate(() => window.getSelection()?.anchorOffset)).toBe(12)
  await editor.press("ControlOrMeta+z")
  await expect(page.getByLabel("Draft text")).not.toHaveText("draft edited")
  await editor.press("ControlOrMeta+Shift+z")
  await expect(editor).toHaveText("draft edited")
  await expect(page.getByLabel("Attachments")).toHaveText("2")
  await send.click()
  await expect(page.getByLabel("Submissions")).toHaveText("1")
})

