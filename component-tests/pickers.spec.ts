import { expect, test, type Route } from "@playwright/test"

test("recent sessions keep keyboard selection, paging, query resets and switching guards", async ({ page }) => {
  await page.goto("/component-tests/pickers.html")
  const input = page.getByRole("combobox")
  const active = page.getByRole("option", { selected: true })
  const opened = page.getByLabel("Opened session")
  await expect(input).toBeFocused()
  await expect(page.getByRole("option")).toHaveCount(12)
  await expect(active).toContainText("Session 1")
  await input.press("ArrowUp")
  await expect(active).toContainText("Session 12")
  await expect(active).toBeInViewport({ ratio: 1 })
  await input.press("ArrowDown")
  await input.press("ArrowDown")
  await expect(active).toContainText("Session 2")
  await expect(active).toBeInViewport({ ratio: 1 })
  await expect(input).toHaveAttribute("aria-activedescendant", (await active.getAttribute("id")) as string)
  await input.press("Shift+ArrowDown")
  await input.press("Control+ArrowUp")
  await expect(active).toContainText("Session 2")
  await page.getByRole("button", { name: "Load more" }).click()
  await expect(page.getByRole("option")).toHaveCount(13)
  await expect(active).toContainText("Session 2")
  await page.getByRole("button", { name: "Remove highlighted session" }).click()
  await expect(page.getByRole("option", { name: /^Session 2\s/ })).toHaveCount(0)
  await expect(active).toContainText("Session 1")
  await page.getByLabel("Switching session").check()
  await input.press("Enter")
  await expect(opened).toBeEmpty()
  await expect(page.getByLabel("Session closes")).toHaveText("0")
  await page.getByLabel("Switching session").uncheck()
  await input.fill("Session 13")
  await expect(page.getByRole("option")).toHaveCount(1)
  await expect(page.getByLabel("Server query")).toHaveText("Session 13")
  await input.dispatchEvent("keydown", { key: "Enter", repeat: true })
  await input.dispatchEvent("keydown", { key: "Enter", isComposing: true })
  await expect(opened).toBeEmpty()
  await input.press("Enter")
  await expect(opened).toHaveText("session-13")
  await expect(page.getByLabel("Session closes")).toHaveText("1")
  await input.fill("no match")
  await expect(page.getByRole("option")).toHaveCount(0)
  await input.press("ArrowDown")
  await input.press("Enter")
  await expect(page.getByLabel("Session closes")).toHaveText("1")
  await page.getByRole("button", { name: "Clear", exact: true }).click()
  await expect(input).toBeFocused()
  await expect(page.getByRole("option")).toHaveCount(12)
  await input.fill("Session 3")
  await expect(page.getByRole("option")).toHaveCount(1)
  await page.getByRole("button", { name: "Reopen sessions" }).click()
  await expect(input).toHaveValue("")
  await expect(page.getByRole("option")).toHaveCount(12)
  await page.getByRole("option", { name: /^Session 3\s/ }).click()
  await expect(opened).toHaveText("session-3")
  await expect(page.getByLabel("Session closes")).toHaveText("2")
})
