import { expect, test } from "@playwright/test"

test("recent sessions keep keyboard selection, paging, query resets and switching guards", async ({ page }) => {
  await page.goto("/component-tests/pickers.html")
  const input = page.getByRole("combobox")
  const active = page.getByRole("option", { selected: true })
  const opened = page.getByLabel("Opened session")
  await expect(input).toBeFocused()
  await expect(page.getByRole("option")).toHaveCount(12)
  await expect(active).toContainText("Session 1")
  await input.press("ArrowUp")
  await expect(active).toContainText("Session 12")
  await input.press("ArrowDown")
  await input.press("ArrowDown")
  await expect(active).toContainText("Session 2")
  await expect(input).toHaveAttribute("aria-activedescendant", (await active.getAttribute("id")) as string)
  await input.press("Shift+ArrowDown")
  await input.press("Control+ArrowUp")
  await expect(active).toContainText("Session 2")
  await page.getByRole("button", { name: "Load more" }).click()
  await expect(page.getByRole("option")).toHaveCount(13)
  await expect(active).toContainText("Session 2")
  await page.getByRole("button", { name: "Remove highlighted session" }).click()
  await expect(page.getByRole("option", { name: /^Session 2\s/ })).toHaveCount(0)
  await expect(active).toContainText("Session 1")
  await page.getByLabel("Switching session").check()
  await input.press("Enter")
  await expect(opened).toBeEmpty()
  await expect(page.getByLabel("Session closes")).toHaveText("0")
  await page.getByLabel("Switching session").uncheck()
  await input.fill("Session 13")
  await expect(page.getByRole("option")).toHaveCount(1)
  await expect(page.getByLabel("Server query")).toHaveText("Session 13")
  await input.dispatchEvent("keydown", { key: "Enter", repeat: true })
  await input.dispatchEvent("keydown", { key: "Enter", isComposing: true })
  await expect(opened).toBeEmpty()
  await input.press("Enter")
  await expect(opened).toHaveText("session-13")
  await expect(page.getByLabel("Session closes")).toHaveText("1")
  await input.fill("no match")
  await expect(page.getByRole("option")).toHaveCount(0)
  await input.press("ArrowDown")
  await input.press("Enter")
  await expect(page.getByLabel("Session closes")).toHaveText("1")
  await page.getByRole("button", { name: "Clear", exact: true }).click()
  await expect(input).toBeFocused()
  await expect(page.getByRole("option")).toHaveCount(12)
  await input.fill("Session 3")
  await expect(page.getByRole("option")).toHaveCount(1)
  await page.getByRole("button", { name: "Reopen sessions" }).click()
  await expect(input).toHaveValue("")
  await expect(page.getByRole("option")).toHaveCount(12)
  await page.getByRole("option", { name: /^Session 3\s/ }).click()
  await expect(opened).toHaveText("session-3")
  await expect(page.getByLabel("Session closes")).toHaveText("2")
})

test("models retain current selection, display-order navigation, focus and Manage with no matches", async ({
  page,
}) => {
  await page.goto("/component-tests/pickers.html?picker=models")
  const trigger = page.getByRole("button", { name: "Models", exact: true })
  const input = page.getByRole("textbox", { name: "Search models" })
  const selected = page.getByLabel("Selected model")
  const active = page.locator("[data-option-key].\\!bg-v2-overlay-simple-overlay-hover")
  await trigger.click()
  await expect(input).toBeFocused()
  await expect(active).toHaveAttribute("data-option-key", "openai:beta")
  await input.press("ArrowDown")
  await expect(active).toHaveText("Manage models")
  await input.press("ArrowDown")
  await expect(active).toHaveText("Zulu")
  await input.press("Control+ArrowDown")
  await expect(active).toHaveText("Alpha")
  await input.press("Shift+ArrowUp")
  await expect(active).toHaveText("Zulu")
  await input.press("Alt+ArrowDown")
  await expect(active).toHaveText("Zulu")
  await input.press("Enter")
  await expect(selected).toHaveText("opencode:zulu")
  await expect(page.getByLabel("Draft")).toBeFocused()
  await expect(page.getByLabel("Draft")).toHaveValue("Keep this draft")
  await trigger.click()
  await input.fill("openai")
  await expect(active).toHaveText("Alpha")
  await input.dispatchEvent("keydown", { key: "Enter", isComposing: true })
  await expect(input).toBeVisible()
  await expect(selected).toHaveText("opencode:zulu")
  await page.getByRole("menuitemradio", { name: "Beta", exact: true }).click()
  await expect(selected).toHaveText("openai:beta")
  await trigger.click()
  await input.press("F4")
  await expect(page.getByRole("menuitemradio", { name: "Beta", exact: true })).toHaveCount(0)
  await expect(active).toHaveText("Zulu")
  await input.fill("no match")
  await expect(page.getByText("No model results", { exact: true })).toBeVisible()
  await expect(active).toHaveText("Manage models")
  await input.press("Enter")
  await expect(page.getByLabel("Managed")).toHaveText("1")
  await expect(input).toHaveCount(0)
  await trigger.click()
  await input.fill("alpha")
  await page.getByRole("button", { name: "Clear", exact: true }).click()
  await expect(input).toBeFocused()
  await expect(input).toHaveValue("")
  await input.press("Escape")
  await expect(page.getByLabel("Model closes")).toHaveText("1")
  await expect(page.getByLabel("Draft")).toBeFocused()
})

test("models without management leave empty searches inert and recover on clear", async ({ page }) => {
  await page.goto("/component-tests/pickers.html?picker=models&manage=false")
  await page.getByRole("button", { name: "Models", exact: true }).click()
  const input = page.getByRole("textbox", { name: "Search models" })
  await input.fill("missing")
  await expect(page.getByRole("menuitem")).toHaveCount(0)
  await expect(page.getByRole("menuitemradio")).toHaveCount(0)
  await input.press("ArrowDown")
  await input.press("Enter")
  await expect(page.getByLabel("Selected model")).toHaveText("openai:beta")
  await expect(input).toBeVisible()
  await page.getByRole("button", { name: "Clear", exact: true }).click()
  await input.press("Enter")
  await expect(page.getByLabel("Selected model")).toHaveText("openai:alpha")
  await expect(page.getByLabel("Draft")).toBeFocused()
})
